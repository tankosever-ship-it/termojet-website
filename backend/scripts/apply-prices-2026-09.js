// ── запобіжники ──────────────────────────────────────────────────────────────
// Товари під активною тимчасовою кампанією (temp-price.cjs) чіпати не можна:
// у них ціна кампанійна, а не прайсова, і 17.09 cron поверне їх у EUR.
function campaignSlugs () {
  const dir = path.dirname(DBP)
  const out = new Set()
  let files = []
  try { files = fs.readdirSync(dir) } catch { return out }
  for (const f of files) {
    if (!/^temp-price-.*\.json$/.test(f)) continue
    try {
      const st = JSON.parse(fs.readFileSync(path.join(dir, f), 'utf8'))
      for (const it of st.items || []) out.add(it.slug)
    } catch { /* пошкоджений стан — краще пропустити, ніж упасти */ }
  }
  return out
}

const skip = campaignSlugs()
if (skip.size) console.log(`Активна цінова кампанія: ${skip.size} товар(ів) під захистом\n`)

const sel = db.prepare('SELECT id, sku, slug, name, price, currency FROM products WHERE sku = ?')
const upd = db.prepare('UPDATE products SET price = ? WHERE id = ?')

let willChange = 0, already = 0
const problems = []

const run = db.transaction(() => {
  for (const [sku, oldP, newP, wantCur = 'UAH'] of PRICES) {
    const r = sel.get(sku)
    if (!r) { problems.push(`${sku} — картки немає в базі`); continue }
    if (skip.has(r.slug)) { problems.push(`${sku} — під тимчасовою кампанією, не чіпаю`); continue }
    if ((r.currency || 'UAH') !== wantCur) { problems.push(`${sku} — валюта ${r.currency}, а очікувалась ${wantCur}`); continue }
    const cur = Number(r.price)
    if (Math.abs(cur - newP) < 0.01) { already++; continue }
    // Ціна мала лишитись такою, якою була на момент розрахунку. Інакше хтось
    // правив її в адмінці після 27.08, і затирати цю правку наосліп не можна.
    if (Math.abs(cur - oldP) > 0.01) {
      problems.push(`${sku} — у базі ${cur.toFixed(2)}, а розрахунок робився з ${oldP.toFixed(2)}; лишаю як є`)
      continue
    }
    console.log(`  ${sku.padEnd(16)} ${cur.toFixed(2).padStart(10)} → ${String(newP).padStart(8)}   ` +
                `+${((newP / cur - 1) * 100).toFixed(1)}%   ${r.name.slice(0, 62)}`)
    willChange++
    if (APPLY) upd.run(newP, r.id)
  }
})
run()

