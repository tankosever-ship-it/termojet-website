/*
 * apply-hbs-modes.js — переписує розділ «Режими роботи» в описі насоса
 * HBS 24-12 у живій БД.
 *
 * У SEO-описі стояли режими Δp-c і Δp-v — це текст від циркуляційних
 * насосів APM/APE, у рециркуляційного HBS таких режимів немає взагалі.
 * Реальні режими взято з інструкції виробника (американська редакція
 * PROZRTED HBS24-12): автоматична стала температура, енергоощадна стала
 * температура, ручний режим, три швидкості, пульт, захист від замерзання.
 *
 * Ідемпотентно: якщо старого розділу в описі немає, скрипт нічого не пише.
 *
 *   docker compose exec -T app node backend/scripts/apply-hbs-modes.js
 */
const path = require('path')
const Database = require('better-sqlite3')

const DBP = path.join(__dirname, '..', 'data', 'termojet.db')
const db = new Database(DBP)

const ID = 'new_38241225'

const OLD = [
  '<h3>Режими роботи AUTO</h3>',
  '<p><strong>Постійний диференційний тиск (Δp-c).</strong> Насос підтримує задану різницю тисків у трубопроводі рециркуляції незалежно від розбору гарячої води. Режим Δp-c оптимальний там, де є кілька точок водозабору, підключених паралельно.</p>',
  '<p><strong>Пропорційний диференційний тиск (Δp-v).</strong> Диференційний тиск знижується пропорційно до зменшення витрати — насос мінімізує споживання в нічний час або при зниженому водорозборі. Режим Δp-v знижує рівень шуму в трубах і витрату електрики при частковому навантаженні.</p>',
  '<p>Вбудований термостат автоматично вимикає насос при досягненні 38°C у зворотному трубопроводі та вмикає його при охолодженні до 33°C — гаряча вода завжди в стані готовності без зайвого перегрівання.</p>',
].join('\n')

const NEW = [
  '<h3>Режими роботи</h3>',
  '<p><strong>Автоматична стала температура.</strong> Іконка світиться помаранчевим. Насос цілодобово тримає гарячу воду напоготові: вмикається, коли вода у зворотному трубопроводі охолола до 33°C, і зупиняється, коли вона нагрілася до 38°C. Це заводське налаштування.</p>',
  '<p><strong>Енергоощадна стала температура.</strong> Іконка світиться зеленим. Той самий цілодобовий цикл, але насос сам знижує уставку, коли гарячою водою давно не користувалися — і не гріє трубу даремно вночі або за відсутності мешканців.</p>',
  '<p><strong>Ручний режим.</strong> Іконка не світиться. Насос робить один цикл: жене воду до заданої температури й вимикається — або через 60 хвилин, якщо температури так і не досягнуто. Зручно, коли гаряча вода потрібна разово.</p>',
  '<p><strong>Три швидкості.</strong> Перемикаються коротким натисканням кнопки, поточна показується швидкістю обертання світлової смуги: що швидше вона біжить, то вища швидкість. Нижча швидкість — тихіша робота й менше споживання.</p>',
  '<p><strong>Пульт у комплекті.</strong> Запуск із пульта тримає температуру протягом години, після чого насос зупиняється.</p>',
  '<p><strong>Захист від замерзання.</strong> Якщо вода в насосі опускається нижче 5°C, він вмикається самостійно й працює, доки температура не підніметься до 10°C.</p>',
].join('\n')

const row = db.prepare('SELECT id, description FROM products WHERE id = ?').get(ID)
if (!row) {
  console.log(`товар ${ID} не знайдено — нічого не робимо`)
  process.exit(0)
}

const description = row.description || ''
if (!description.includes(OLD)) {
  console.log('розділ режимів уже переписаний — змін не потрібно')
  process.exit(0)
}

db.prepare('UPDATE products SET description = ? WHERE id = ?')
  .run(description.replace(OLD, NEW), ID)
console.log('розділ «Режими роботи» оновлено')
