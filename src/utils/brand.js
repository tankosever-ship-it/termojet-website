// Бренд товару. Майже весь каталог — власне виробництво Termojet, і бейдж
// «Власне виробництво» на картці товару стояв безумовно. Щойно в каталозі
// з'явився товар чужого бренду (вітринна труба SPY), цей бейдж став неправдою.
//
// Ознака бренду — ключ «Бренд» у БАЗОВИХ (українських) характеристиках. Саме
// базових: у перекладених `specs_<мова>` ключ інший («Marcă», «Marka», «Marque»),
// тож перевірка по них мовчки провалювалась би на всіх мовах, крім української.
// Товар без цього ключа вважається власним — так поводяться всі наявні картки.
export const OWN_BRAND = 'Termojet'

export function productBrand(p) {
  return String(p?.specs?.['Бренд'] || '').trim()
}

export function isOwnBrand(p) {
  const brand = productBrand(p)
  return !brand || brand.toLowerCase() === OWN_BRAND.toLowerCase()
}
